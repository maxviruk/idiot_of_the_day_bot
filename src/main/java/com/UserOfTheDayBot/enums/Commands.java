package com.UserOfTheDayBot.enums;

public enum Commands {
    start,        // приветствие/справка
    help,         // справка
    reg,          // зарегистрироваться в игре
    unreg,        // выйти из игры самому
    run,          // разыграть "красавчика дня"
    loser,        // разыграть "неудачника дня"
    stat_user,    // статистика "красавчиков" (аргумент: month / year)
    stat_loser,   // статистика "неудачников" (аргумент: month / year)
    me,           // личная статистика и серии
    history,      // история победителей (issue: подгрузка истории)
    auto,         // (админ) авторозыгрыш по расписанию: /auto 10:00 | /auto off
    remove,       // удалить игрока (для админов) — issue #2
    reset         // сбросить статистику чата (для админов, с подтверждением) — issue #5
}
